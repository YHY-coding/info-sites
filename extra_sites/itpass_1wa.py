def build(page, write):
    slug = META["slug"]
    p = lambda path, title, desc, body: page(SITE, f"{slug}/{path}", title, desc, body, NAV, DISC)
    cards = "".join(
        f"<div class='card'><a href='ep{n:02d}.html'><strong>{esc(series)} 第1話: {esc(title)}</strong></a><br>{esc(one)}</div>"
        for n, series, title, one, _, _, _ in EPS)
    p("index.html", "ITパスポート 1話完結ガイド|分野別の第1話",
      "ITパスポートの入口。分野の違う第1話を、たとえ話で短く読めます。続きは詳しい単元ページへ。",
      "<h1>ITパスポート 1話完結ガイド</h1>"
      "<p>分野ごとに、まず<strong>第1話</strong>だけを集めました。1話は、2〜3分で読めます。気になった話から、どうぞ。</p>"
      + cards +
      "<p>続きは、詳しい<a href='../it-shikaku/itpass-units/index.html'>単元別ガイド</a>と、"
      "<a href='../it-shikaku/itpass-quiz/index.html'>オリジナル4択問題集</a>で。</p>")
    for i, (n, series, title, one, taste, body, more) in enumerate(EPS):
        prev = f"<a href='ep{EPS[i - 1][0]:02d}.html'>« 前の話</a> " if i > 0 else ""
        nxt = f" <a href='ep{EPS[i + 1][0]:02d}.html'>次の話 »</a>" if i + 1 < len(EPS) else ""
        more_html = "".join(f"<li><a href='{u}'>{esc(t)}</a></li>" for u, t in more)
        p(f"ep{n:02d}.html", f"{series} 第1話: {title}|ITパスポート",
          f"ITパスポート{series}の第1話。{one}",
          f"<p class='note'>{esc(series)} 第1話</p><h1>{esc(title)}</h1>"
          f"<div class='card'><strong>一言で言うと</strong><br>{esc(one)}</div>"
          f"<div class='card'><strong>たとえるなら</strong><br>{esc(taste)}</div>"
          + body +
          f"<h2>続きを読む</h2><ul class='links'>{more_html}<li><a href='index.html'>ほかの第1話を見る</a></li></ul>"
          f"<p>{prev}{nxt}</p>")
